    public static boolean active() {
        String l = Locale.getDefault().getLanguage();
        if (!l.equals(lang)) {
            lang = l;
            if ("zh".equals(l)) load();
            else exact = null;
        }
        return exact != null;
    }

    public static CharSequence t(CharSequence s) {
        if (!(s instanceof String)) return s;
        return t((String) s);
    }

    public static String t(String s) {
        if (s == null || s.isEmpty() || !active()) return s;
        String r = exact.get(s);
        if (r != null) return r;
        for (Object[] p : patterns) {
            Matcher m = ((Pattern) p[0]).matcher(s);
            if (m.matches()) {
                String out = (String) p[1];
                for (int i = 1; i <= m.groupCount(); i++) out = out.replace("{" + (i - 1) + "}", t(m.group(i)));
                return out;
            }
        }
        for (String[] p : prefixes) if (s.startsWith(p[0]) && s.length() > p[0].length()) return p[1] + s.substring(p[0].length());
        if (s.endsWith("…")) {
            String b = exact.get(s.substring(0, s.length() - 1));
            if (b != null) return b + "…";
        }
        return s;
    }

    private static synchronized void load() {
        if (exact != null) return;
        Map<String, String> m = new HashMap<>();
        for (int i = 0; i + 1 < ZH.length; i += 2) m.put(ZH[i], ZH[i + 1]);
        List<String[]> pre = new ArrayList<>();
        for (int i = 0; i + 1 < ZH_PREFIX.length; i += 2) pre.add(new String[]{ZH_PREFIX[i], ZH_PREFIX[i + 1]});
        pre.sort((a, b) -> b[0].length() - a[0].length());
        List<Object[]> pat = new ArrayList<>();
        for (int i = 0; i + 1 < ZH_PATTERN.length; i += 2) pat.add(new Object[]{Pattern.compile(ZH_PATTERN[i]), ZH_PATTERN[i + 1]});
        prefixes = pre;
        patterns = pat;
        exact = m;
    }

